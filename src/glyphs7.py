"""The 7x9 heading face, hand-defined glyph by glyph.

Same idea as the 5x8 body face in glyphs.py, one size up and two cells thick
in the stems so it still reads as display type when every pixel is a
contribution square. Cells are 7 wide by 11 tall: rows 0-8 are cap height,
rows 9-10 are the descender. Lowercase x-height starts at row 2.

Imported by glyphs.py as F7. Nothing here is derived from a font file.
"""

F7 = {}
W7, H7 = 7, 11
CAPR7 = 9   # cap line to baseline inclusive


def _d7(spec, rows_expected=9):
    for chunk in spec.strip().split("\n\n"):
        lines = chunk.split("\n")
        ch = " " if lines[0] == "SPACE" else lines[0]
        rows = lines[1:]
        assert len(rows) == rows_expected, (ch, len(rows))
        assert all(len(r) == W7 for r in rows), (ch, [len(r) for r in rows])
        F7[ch] = rows + ["." * W7] * (H7 - rows_expected)


